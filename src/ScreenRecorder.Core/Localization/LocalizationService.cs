namespace ScreenRecorder.Core.Localization;

public partial class LocalizationService : ILocalizationService
{
    private static readonly Lazy<LocalizationService> _instance = new(() => new LocalizationService());
    public static LocalizationService Instance => _instance.Value;

    private AppLanguage _currentLanguage = AppLanguage.ZhTw;

    public event EventHandler<AppLanguage>? LanguageChanged;

    public AppLanguage CurrentLanguage
    {
        get => _currentLanguage;
        set
        {
            if (_currentLanguage != value)
            {
                _currentLanguage = value;
                LanguageChanged?.Invoke(this, value);
            }
        }
    }

    public string this[string key] => GetString(key);

    public string GetString(string key)
    {
        var dict = _currentLanguage switch
        {
            AppLanguage.ZhTw => ZhTwDictionary,
            AppLanguage.JaJp => JaJpDictionary,
            _ => EnUsDictionary
        };
        if (dict.TryGetValue(key, out var val))
        {
            return val;
        }

        // Fallback to ZhTw
        if (ZhTwDictionary.TryGetValue(key, out var fallbackVal))
        {
            return fallbackVal;
        }

        return key;
    }

    public string GetFormatted(string key, params object[] args)
    {
        var template = GetString(key);
        try
        {
            return string.Format(template, args);
        }
        catch
        {
            return template;
        }
    }

