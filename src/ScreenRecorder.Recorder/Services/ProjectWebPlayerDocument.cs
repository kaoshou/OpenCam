using ScreenRecorder.Core.Projects;
using System.Net;
using System.Reflection;
using System.Text.Json;

namespace ScreenRecorder.Recorder.Services;

public sealed record WebPlayerGenerator(string Name, string Version, string ProjectUrl);
public sealed record WebPlayerChapter(Guid Id, string Title, double Start, double End);
public sealed record WebPlayerData(string Format, int SchemaVersion, WebPlayerGenerator Generator,
    string Entry, string Media, string Title, WebPlayerChapter[] Chapters);

public static class ProjectWebPlayerDocument
{
    public static WebPlayerData CreateData(RecordingProject project)
    {
        var timeline = ProjectTimeline.Build(project);
        var names = project.Clips.ToDictionary(c => c.Id, c => c.Name);
        var version = typeof(ProjectWebPlayerDocument).Assembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>()?
            .InformationalVersion.Split('+')[0] ?? "unknown";
        return new("opencam.web-player", 1, new("OpenCam", version, "https://github.com/kaoshou/OpenCam"),
            "index.html", "media.mp4", project.Name, timeline.Clips.Select(c => new WebPlayerChapter(
                c.ClipId, names[c.ClipId], c.StartTicks / (double)TimeSpan.TicksPerSecond,
                c.EndTicks / (double)TimeSpan.TicksPerSecond)).ToArray());
    }

    // Strict JSON assignment: consumers can parse the data without executing JavaScript.
    // The default JSON encoder escapes HTML-sensitive characters; never use relaxed encoding here.
    public static string CreateScript(WebPlayerData data) =>
        "// Generated by OpenCam — https://github.com/kaoshou/OpenCam\nwindow.OpenCamPlayerData = " +
        JsonSerializer.Serialize(data, new JsonSerializerOptions { PropertyNamingPolicy = JsonNamingPolicy.CamelCase, WriteIndented = true }) + ";\n";

    public static string CreateHtml(WebPlayerData data)
    {
        using var stream = typeof(ProjectWebPlayerDocument).Assembly.GetManifestResourceStream("OpenCam.WebPlayer.html")
            ?? throw new InvalidOperationException("Web player template is unavailable.");
        using var reader = new StreamReader(stream);
        return reader.ReadToEnd().Replace("%%TITLE%%", WebUtility.HtmlEncode(data.Title), StringComparison.Ordinal);
    }
}
