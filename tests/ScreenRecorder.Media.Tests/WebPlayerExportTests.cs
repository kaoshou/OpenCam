    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public async Task ExportPublishesThreeFilesAndDoesNotOverwriteAnotherPackage(bool cancel)
    {
        var root = Directory.CreateTempSubdirectory("opencam-web-test-");
        try
        {
            await using var owner = await new JsonProjectStore().CreateAsync(root.FullName, "test");
            var p = Fixture() with { ProjectId = owner.Current.ProjectId };
            var exporter = new ProjectWebPlayerExporter(new VideoFixtureExporter(cancel));
            var existing = Path.Combine(root.FullName, "index.html");
            await File.WriteAllTextAsync(existing, "keep");
            if (cancel)
            {
                await Assert.ThrowsAnyAsync<OperationCanceledException>(() => exporter.ExportAsync(owner, p,
                    root.FullName, Guid.NewGuid(), new Progress<double>(), new CancellationTokenSource().Token));
                Assert.Empty(Directory.GetFiles(root.FullName, "opencam-player.js", SearchOption.AllDirectories));
                Assert.Single(Directory.GetFiles(root.FullName, "index.html", SearchOption.AllDirectories));
                Assert.Empty(Directory.GetFiles(root.FullName, "media.mp4", SearchOption.AllDirectories));
            }
            else
            {
                var result = await exporter.ExportAsync(owner, p, root.FullName, Guid.NewGuid(), new Progress<double>(), default);
                Assert.True(result.Success, result.Error);
                Assert.Equal("index.html", Path.GetFileName(result.FinalPath));
                var folder = Path.GetDirectoryName(result.FinalPath)!;
                Assert.Equal(3, Directory.GetFiles(folder).Length);
                Assert.Equal("verified video", await File.ReadAllTextAsync(Path.Combine(folder, "media.mp4")));
                var script = await File.ReadAllTextAsync(Path.Combine(folder, "opencam-player.js"));
                var json = script[(script.IndexOf(" = ", StringComparison.Ordinal) + 3)..].Trim().TrimEnd(';');
                using var data = JsonDocument.Parse(json);
                Assert.Equal(2, data.RootElement.GetProperty("chapters").GetArrayLength());
                var html = await File.ReadAllTextAsync(result.FinalPath!);
                Assert.Contains("https://github.com/kaoshou/OpenCam", html);
                Assert.Contains("src=\"opencam-player.js\"", html);
                Assert.DoesNotContain("fetch(", html);
                Assert.Contains("&lt;測試&gt;", html);
            }
            Assert.Equal("keep", await File.ReadAllTextAsync(existing));
        }
        finally { Directory.Delete(root.FullName, true); }
    }

    [Fact]
    public async Task CancelAfterVerifiedVideoCleansOnlyOwnedPackageFiles()
    {
        var root = Directory.CreateTempSubdirectory("opencam-web-cancel-");
        try
        {
            await using var owner = await new JsonProjectStore().CreateAsync(root.FullName, "cancel");
            var p = Fixture() with { ProjectId = owner.Current.ProjectId };
            using var cancellation = new CancellationTokenSource();
            var exporter = new ProjectWebPlayerExporter(new VideoFixtureExporter(false, cancellation));
            var original = Path.Combine(root.FullName, "original.mkv");
            await File.WriteAllTextAsync(original, "original recording");
            await Assert.ThrowsAnyAsync<OperationCanceledException>(() => exporter.ExportAsync(owner, p, root.FullName,
                Guid.NewGuid(), new Progress<double>(), cancellation.Token));
            Assert.Empty(Directory.GetFiles(root.FullName, "*.mp4", SearchOption.AllDirectories));
            Assert.Empty(Directory.GetFiles(root.FullName, "index.html", SearchOption.AllDirectories));
            Assert.Empty(Directory.GetFiles(root.FullName, "opencam-player.js", SearchOption.AllDirectories));
            Assert.Equal("original recording", await File.ReadAllTextAsync(original));
        }
        finally { Directory.Delete(root.FullName, true); }
    }

    internal sealed class VideoFixtureExporter(bool cancel, CancellationTokenSource? cancelAfterVideo = null) : IRecordingContentExporter
    {
        public async Task<RecordingExportResult> ExportAsync(IProjectHandle owner, RecordingProject snapshot,
            string directory, Guid id, IProgress<double> progress, CancellationToken ct)
        {
            if (cancel) throw new OperationCanceledException(ct);
            var path = Path.Combine(directory, "verified.mp4");
            await File.WriteAllTextAsync(path, "verified video", ct);
            cancelAfterVideo?.Cancel();
            return new(true, path, null);
        }
    }
