    [Avalonia.Headless.XUnit.AvaloniaFact]
    public async Task EditorExportMenuOffersMp4GifAndWebWithInheritedLabels()
    {
        var state = new ScreenRecorder.Infrastructure.IPC.ProjectSnapshot(Guid.NewGuid(), "menu", "/test", 0, 0,
            ProjectMode.Ready, 1, false, false);
        var vm = new ScreenRecorder.UI.Projects.ProjectWorkspaceViewModel(new ScreenRecorder.UI.Projects.ProjectClient(
            (_, _, _) => Task.FromResult(new ScreenRecorder.Infrastructure.IPC.IpcResponse { Success = true,
                DataJson = JsonSerializer.Serialize(new ScreenRecorder.Infrastructure.IPC.ProjectReply(true, null, state)) })));
        vm.ApplyReply(new(true, null, state));
        var window = new ScreenRecorder.UI.Projects.ProjectWorkspaceView { DataContext = vm };
        window.Show();
        try
        {
            var button = window.FindControl<Avalonia.Controls.Button>("ExportButton")!;
            Assert.True(button.IsEnabled);
            var flyout = Assert.IsType<Avalonia.Controls.MenuFlyout>(button.Flyout);
            flyout.ShowAt(button);
            Avalonia.Threading.Dispatcher.UIThread.RunJobs();
            var items = flyout.Items.OfType<Avalonia.Controls.MenuItem>().ToArray();
            Assert.Equal(3, items.Length);
            Assert.Equal(vm.Strings["ProjectExportVideo"], items[0].Header);
            Assert.Equal(vm.Strings["ProjectExportGif"], items[1].Header);
            Assert.Equal(vm.Strings["ProjectExportWeb"], items[2].Header);
            flyout.Hide();
        }
        finally { await window.RequestCloseAsync(); }
    }

    [Fact]
    public async Task WebPlayerExportFlowsThroughIpcAndKeepsPausedProjectEditable()
    {
        await using var scope = new RecordingScope();
        await using var coordinator = new ProjectRecordingCoordinator(scope.Recorder, new JsonProjectStore(),
            new ProjectProbeStub(), new WebPlayerExportTests.VideoFixtureExporter(false));
        var dispatcher = new ProjectIpcDispatcher(coordinator);
        var vm = new ScreenRecorder.UI.Projects.ProjectWorkspaceViewModel(new ScreenRecorder.UI.Projects.ProjectClient(
            (command, request, ct) => dispatcher.DispatchAsync(new() { MessageType = command, PayloadJson = JsonSerializer.Serialize(request) })));
        await vm.CreateAsync(scope.Configuration.OutputDirectory, "web IPC");
        await vm.StartAsync(scope.Configuration);
        await vm.PauseAsync();
        await vm.SaveAsync();
        Assert.True(vm.CanExport, vm.Error);
        await vm.ExportWebPlayerAsync(scope.Configuration.OutputDirectory);
        Assert.Null(vm.Error);
        await UntilAsync(() => coordinator.ExportStatus?.State == RecordingExportState.Succeeded);
        var output = coordinator.ExportStatus!.FinalPath!;
        Assert.Equal("index.html", Path.GetFileName(output));
        Assert.True(File.Exists(Path.Combine(Path.GetDirectoryName(output)!, "media.mp4")));
        Assert.Equal(ProjectMode.Paused, coordinator.Mode);
        var invalid = await coordinator.ExportAsync(scope.Configuration.OutputDirectory, coordinator.Current!.Revision,
            Guid.NewGuid(), pathIsFile: true, webPlayer: true);
        Assert.False(invalid.Success);
        await vm.FinishAsync();
    }
